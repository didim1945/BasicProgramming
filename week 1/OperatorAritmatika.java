public class OperatorAritmatika {
    public static void main(String[] args) {
        int a = 20;
        int b = 10;
        System.out.println ("Operator Aritmatika");
        System.out.println ("Belajar Operator Aritmatika");
        System.out.println ("Bilangan pertama =" +a);
        System.out.println ("Bilangan kedua =" +b);
        System.out.println ("Hasil penjumlahan ="+ (a+b));
        System.out.println ("Hasil pengurangan ="+ (a-b));
        System.out.println ("Hasil perkalian ="+ (a*b));
        System.out.println ("Hasil pembagian ="+ (a/b)); 
        System.out.println ("Hasil sisa bagi ="+ (a%b));
    }
}

